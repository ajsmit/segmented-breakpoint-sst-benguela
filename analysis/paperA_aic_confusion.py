#!/usr/bin/env python3
"""paperA_aic_confusion.py -- Stage 3 Task 3.3: pairwise 2x2 confusion
matrices between AIC, AICc, and BIC at Delta >= 4 on the smoke subset.

Smoke subset: Cape Columbine, all 4 products, DJF 2020 (from Task 3.2).
The Delta >= 4 threshold is the Burnham & Anderson (2002) "considerable
evidence" bar for the two-segment model over the one-segment model,
where K_TWO_SEGMENT - K_ONE_SEGMENT = 2 so 2 * (Delta k) = 4.

Outputs:
  results/tables/table_s_aic_aicc_bic.csv -- long-format confusion
    matrix entries for the supplement table S_AIC_AICC_BIC.

Verification:
  - Each matrix row and column totals match the per-product profile count.
  - AIC and AICc agree on OSTIA / OSPO (n approx 100, AICc correction
    approx 0.4); they disagree on AVHRR_OI / MW_OI (n approx 20, AICc
    correction approx 2.5) in the direction that AICc is more conservative
    than AIC about accepting the two-segment model.

Run from the release repository root:
    python3 analysis/paperA_aic_confusion.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paperA_common as P


SRC_CSV = P.PAPERA_ROOT / "diagnostics/smoke_aic_aicc_bic.csv"
OUT_CSV = P.PAPERA_ROOT / "tables/table_s3_aic_aicc_bic.csv"
OUT_LATEX = P.PAPERA_ROOT / "tables/table_s3_aic_aicc_bic.tex"

THRESHOLD = P.DELTA_AIC_BAR  # = 4.0


def confusion(df: pd.DataFrame, col_x: str, col_y: str,
              name_x: str, name_y: str) -> pd.DataFrame:
    """Build long-format 2x2 confusion entries for (col_x, col_y) >= THRESHOLD.

    Returns rows with (rule_x, rule_y, x_ge_threshold, y_ge_threshold, n)."""
    valid = df.dropna(subset=[col_x, col_y])
    x_ge = (valid[col_x] >= THRESHOLD)
    y_ge = (valid[col_y] >= THRESHOLD)
    rows = []
    for xv in (True, False):
        for yv in (True, False):
            n = int(((x_ge == xv) & (y_ge == yv)).sum())
            rows.append({
                "rule_x": name_x,
                "rule_y": name_y,
                f"{name_x}_ge_{THRESHOLD:g}": xv,
                f"{name_y}_ge_{THRESHOLD:g}": yv,
                "n_profiles": n,
            })
    return pd.DataFrame(rows)


def print_matrix(df: pd.DataFrame, col_x: str, col_y: str,
                 name_x: str, name_y: str, header: str) -> None:
    valid = df.dropna(subset=[col_x, col_y])
    x_ge = (valid[col_x] >= THRESHOLD)
    y_ge = (valid[col_y] >= THRESHOLD)
    n11 = int((x_ge & y_ge).sum())
    n10 = int((x_ge & ~y_ge).sum())
    n01 = int((~x_ge & y_ge).sum())
    n00 = int((~x_ge & ~y_ge).sum())
    total = n11 + n10 + n01 + n00
    print(f"\n  --- {header} (total {total:,} profiles) ---")
    print(f"             {name_y}>={THRESHOLD:g}   {name_y}<{THRESHOLD:g}    row total")
    print(f"  {name_x}>={THRESHOLD:g}   {n11:>7,}  {n10:>7,}  {n11+n10:>10,}")
    print(f"  {name_x}<{THRESHOLD:g}    {n01:>7,}  {n00:>7,}  {n01+n00:>10,}")
    print(f"  col total {n11+n01:>7,}  {n10+n00:>7,}  {total:>10,}")
    agree_pct = (n11 + n00) / total * 100 if total else 0.0
    print(f"  agreement: {agree_pct:.1f}% (both accept or both reject)")


def main() -> None:
    df = pd.read_csv(SRC_CSV)
    print(f"[smoke] {len(df):,} profiles loaded from {SRC_CSV}\n")

    pairs = [
        ("delta_aic_paperA",  "delta_aicc",  "AIC",  "AICc"),
        ("delta_aic_paperA",  "delta_bic",   "AIC",  "BIC"),
        ("delta_aicc",        "delta_bic",   "AICc", "BIC"),
    ]
    parts = []
    for col_x, col_y, name_x, name_y in pairs:
        # Per-product matrices
        for product in P.PRODUCTS:
            sub = df[df["product"] == product]
            if sub.empty:
                continue
            print_matrix(sub, col_x, col_y, name_x, name_y,
                         f"{name_x} vs {name_y}  ({product}, n median = "
                         f"{int(sub['n_eff'].median())})")
            c = confusion(sub, col_x, col_y, name_x, name_y)
            c["product"] = product
            parts.append(c)

    # Long-format table
    out = pd.concat(parts, ignore_index=True)
    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    out.to_csv(OUT_CSV, index=False)
    print(f"\n[output csv]   {OUT_CSV}  ({len(out)} confusion-entry rows)")

    # LaTeX fragment: 3 pairs × 4 products, presented as a long-form table
    lines = [
        r"% S_AIC_AICC_BIC -- generated by paperA_aic_confusion.py",
        r"% Smoke subset: Cape Columbine DJF 2020, all 4 products.",
        r"\begin{table}[!htbp]",
        r"\centering",
        r"\caption{AIC, AICc, and BIC side-by-side comparison on the Cape Columbine DJF 2020 smoke subset across all four SST products. X-only and Y-only columns count profiles accepted by the first and second rule in each rule pair, respectively.}",
        r"\label{tab:supp_aic_aicc_bic}",
        r"\small",
        r"\begin{tabular}{llrrrrr}",
        r"\toprule",
        r"Rule pair & Product & Both reject & X-only & Y-only & Both accept & Agreement (\%) \\",
        r"\midrule",
    ]
    for pair_idx, (col_x, col_y, name_x, name_y) in enumerate(pairs):
        for product in P.PRODUCTS:
            sub = df[df["product"] == product].dropna(subset=[col_x, col_y])
            if sub.empty:
                continue
            x_ge = sub[col_x] >= THRESHOLD
            y_ge = sub[col_y] >= THRESHOLD
            n11 = int((x_ge & y_ge).sum())
            n10 = int((x_ge & ~y_ge).sum())
            n01 = int((~x_ge & y_ge).sum())
            n00 = int((~x_ge & ~y_ge).sum())
            total = n11 + n10 + n01 + n00
            agree = (n11 + n00) / total * 100 if total else 0.0
            lines.append(
                f"{name_x} vs {name_y} & {product.replace('_', r'\_')} & "
                f"{n00:,} & {n10:,} & {n01:,} & {n11:,} & {agree:.1f} \\\\"
            )
        if pair_idx < len(pairs) - 1:
            lines.append(r"\midrule")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table}")
    OUT_LATEX.write_text("\n".join(lines) + "\n")
    print(f"[output latex] {OUT_LATEX}")


if __name__ == "__main__":
    main()
