#!/usr/bin/env python3
"""paperA_sensitivity_survival.py -- Stage 4 Task 4.3: headline-finding
survival summary across the six sensitivity axes.

Three headline findings of paperA:
  F1: Luderitz r sign-inversion at d_0 = 50 km (r < 0 on OSTIA and OSPO).
  F2: P(d_0 < x_b) >= 0.5 at d_0 = 50 km for at least 4 of 5 cells
      (on OSTIA at baseline; checked on OSTIA at each grid point).
  F3: sBUS SST-structure-only fraction in 0.25-0.32 range
      -- requires the wind detector (Stage 5); marked as DEFERRED here.

For each axis, scan all axis values (excluding the baseline that's
already in the manuscript). "Survives" if the finding holds at every
non-baseline grid value; otherwise "breaks" with a notes column naming
the grid value(s) that flip the finding.

Output: results/tables/table_s_sens_summary.csv

Run from the release repository root:
    python3 analysis/paperA_sensitivity_survival.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paperA_common as P
import paperA_sensitivity_grid as G


SRC_PARQUET = P.ROOT / "data/outputs/uidx/paperA_sensitivity/grid_results.parquet"
OUT_CSV = P.PAPERA_ROOT / "tables/table_s_sens_summary.csv"
OUT_LATEX = P.PAPERA_ROOT / "tables/table_s_sens_summary.tex"


def check_F1(sub: pd.DataFrame, axis_value: str) -> tuple[bool, str]:
    """F1: Luderitz r_Ain_UIsst_d50 negative on OSTIA and OSPO at this grid value."""
    rows = sub[(sub["cell"] == "Luderitz") & (sub["product"].isin(["OSTIA", "OSPO"]))]
    rs = rows["r_Ain_UIsst_d50"]
    if rs.isna().all():
        return (False, f"r undefined at {axis_value}")
    holds = (rs < 0).all()
    if holds:
        return (True, f"r OSTIA={rs.iloc[0]:+.3f}, OSPO={rs.iloc[1]:+.3f}"
                if len(rs) >= 2 else f"r={rs.iloc[0]:+.3f}")
    return (False, f"r OSTIA={rs.iloc[0]:+.3f}, OSPO={rs.iloc[1]:+.3f}"
            if len(rs) >= 2 else f"r={rs.iloc[0]:+.3f}")


def check_F2(sub: pd.DataFrame, axis_value: str) -> tuple[bool, str]:
    """F2: P(x_b > 50 km) >= 0.5 on OSTIA at >= 4 of 5 cells."""
    ostia = sub[sub["product"] == "OSTIA"]
    if ostia.empty:
        return (False, "no OSTIA rows")
    ge_05 = (ostia["P_d0_lt_xb_d50"] >= 0.5)
    n_cells_pass = int(ge_05.sum())
    holds = n_cells_pass >= 4
    return (holds, f"{n_cells_pass}/{len(ostia)} cells with P >= 0.5")


def axis_summary(grid: pd.DataFrame, axis: str) -> dict:
    values = [str(v) for v in G.AXIS_DEFS[axis]]
    baseline = str(G.AXIS_BASELINE[axis])
    f1_results = []
    f2_results = []
    for v in values:
        sub = grid[(grid["axis"] == axis) & (grid["axis_value"] == v)]
        h1, n1 = check_F1(sub, v)
        h2, n2 = check_F2(sub, v)
        f1_results.append((v, h1, n1))
        f2_results.append((v, h2, n2))

    def fmt(results: list[tuple[str, bool, str]]) -> tuple[str, str]:
        n_pass = sum(1 for v, h, _ in results if h)
        # "breaks" = values where finding fails
        breaks = [f"{v} ({n})" for v, h, n in results if not h]
        if not breaks:
            status = "preserved"
            notes = (f"{n_pass}/{len(results)} grid values all preserve "
                     f"(baseline = {baseline})")
        else:
            status = f"breaks at {len(breaks)}/{len(results)}"
            notes = "fails at: " + "; ".join(breaks)
        return (status, notes)

    f1_status, f1_notes = fmt(f1_results)
    f2_status, f2_notes = fmt(f2_results)
    return {
        "axis": axis,
        "baseline": baseline,
        "n_grid_values": len(values),
        "F1_Luderitz_sign_inversion": f1_status,
        "F1_notes": f1_notes,
        "F2_P_d0_lt_xb_cells": f2_status,
        "F2_notes": f2_notes,
        "F3_sBUS_sst_only_fraction": "DEFERRED (Stage 5 wind detector)",
        "F3_notes": "Requires wind classifier; populated by Stage 5 paired-classifier task.",
    }


def main() -> None:
    grid = pd.read_parquet(SRC_PARQUET)
    print(f"[loaded] {len(grid):,} grid rows\n")

    summaries = [axis_summary(grid, axis) for axis in G.AXIS_DEFS]
    df = pd.DataFrame(summaries)
    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(OUT_CSV, index=False)
    print(f"[output csv] {OUT_CSV}\n")
    for col in ["axis", "F1_Luderitz_sign_inversion", "F1_notes",
                "F2_P_d0_lt_xb_cells", "F2_notes"]:
        print(f"  {col}")
        for _, r in df.iterrows():
            print(f"    [{r['axis']:<22s}] {r[col]}")
        print()

    # LaTeX fragment (compact 6x3 + notes)
    lines = [
        r"% S_SENS_SUMMARY -- generated by paperA_sensitivity_survival.py",
        r"\begin{tabular}{lllll}",
        r"\toprule",
        r"Axis & F1 (L\"uderitz $r_{50}<0$) & F2 ($\ge 4/5$ cells $x_b>50$\,km) & "
        r"F3 (sBUS SST-only) & Notes \\",
        r"\midrule",
    ]
    for _, r in df.iterrows():
        axis_disp = r["axis"].replace("_", r"\_")
        f1 = r["F1_Luderitz_sign_inversion"]
        f2 = r["F2_P_d0_lt_xb_cells"]
        f3 = r["F3_sBUS_sst_only_fraction"]
        notes = (r["F1_notes"][:60] + ("..." if len(r["F1_notes"]) > 60 else "")).replace("_", r"\_")
        lines.append(f"{axis_disp} & {f1} & {f2} & {f3} & {notes} \\\\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    OUT_LATEX.write_text("\n".join(lines) + "\n")
    print(f"[output latex] {OUT_LATEX}")


if __name__ == "__main__":
    main()
